
from backend.database import get_connection


def get_total_revenue():
    with get_connection() as conn:
        row = conn.execute("""
            SELECT
                ROUND(COALESCE(SUM(revenue), 0), 2) AS total_revenue,
                COUNT(*) AS eligible_transactions
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
        """).fetchone()

    return {
        "total_revenue": row["total_revenue"],
        "eligible_transactions": row["eligible_transactions"]
    }


def get_top_product():
    with get_connection() as conn:
        row = conn.execute("""
            SELECT product,
                   ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
            GROUP BY product
            ORDER BY revenue DESC, product ASC
            LIMIT 1
        """).fetchone()

    if row is None:
        return None

    return {
        "product": row["product"],
        "revenue": row["revenue"]
    }


def get_product_revenue():
    """Return revenue generated by each product."""
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT
                product,
                ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
              AND product IS NOT NULL
            GROUP BY product
            ORDER BY revenue DESC, product ASC
        """).fetchall()

    return [
        {
            "product": row["product"],
            "revenue": row["revenue"]
        }
        for row in rows
    ]


def get_region_revenue():
    """Return revenue generated by each region."""
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT
                region,
                ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
              AND region IS NOT NULL
            GROUP BY region
            ORDER BY revenue DESC, region ASC
        """).fetchall()

    return [
        {
            "region": row["region"],
            "revenue": row["revenue"]
        }
        for row in rows
    ]

def get_monthly_revenue():
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT
                strftime('%Y-%m', order_date) AS month,
                ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
            GROUP BY strftime('%Y-%m', order_date)
            ORDER BY month
        """).fetchall()

    return [
        {"month": row["month"], "revenue": row["revenue"]}
        for row in rows
    ]


def get_top_region():
    with get_connection() as conn:
        row = conn.execute("""
            SELECT region,
                   ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
              AND region IS NOT NULL
            GROUP BY region
            ORDER BY revenue DESC, region ASC
            LIMIT 1
        """).fetchone()

    if row is None:
        return None

    return {
        "region": row["region"],
        "revenue": row["revenue"]
    }


def compare_months(month_a, month_b):
    # Expected format: YYYY-MM
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT
                strftime('%Y-%m', order_date) AS month,
                ROUND(SUM(revenue), 2) AS revenue
            FROM sales_transactions
            WHERE is_eligible_for_revenue = 1
              AND strftime('%Y-%m', order_date) IN (?, ?)
            GROUP BY strftime('%Y-%m', order_date)
        """, (month_a, month_b)).fetchall()

    revenue_by_month = {
        row["month"]: row["revenue"]
        for row in rows
    }

    if month_a not in revenue_by_month:
        return {"error": f"No eligible revenue data for {month_a}"}

    if month_b not in revenue_by_month:
        return {"error": f"No eligible revenue data for {month_b}"}

    revenue_a = revenue_by_month[month_a]
    revenue_b = revenue_by_month[month_b]
    difference = round(revenue_b - revenue_a, 2)

    if revenue_a != 0:
        percentage_change = round(
            (difference / revenue_a) * 100, 2
        )
    else:
        percentage_change = None

    return {
        "month_a": month_a,
        "revenue_a": revenue_a,
        "month_b": month_b,
        "revenue_b": revenue_b,
        "difference": difference,
        "percentage_change": percentage_change
    }


